-- Live ink previews: publish page-head changes for RLS-filtered realtime.
begin;

do $$
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    create publication supabase_realtime;
  end if;
end
$$;

do $$
begin
  if exists (
    select 1 from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relname = 'ink_page_heads'
  ) and not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'ink_page_heads'
  ) then
    alter publication supabase_realtime add table public.ink_page_heads;
  end if;
end
$$;

commit;
